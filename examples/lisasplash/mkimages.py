#!/usr/bin/env python3
"""mkimages.py - splash_images.h from calvin.txt and ttlogo.txt (rows of
'#' lit and '.' dark): each image as 1 bpp rows, MSB first (NX_PACKEDMSFIRST),
a row padded to whole bytes.  calvin.txt is Calvin from the LISA tile's
art (ttsky26d harden/art/calvin_nocircle/source.png, scaled to 64 rows);
ttlogo.txt a clean drawing of the Tiny Tapeout logo's ring and TT.

  python3 mkimages.py > splash_images.h"""
import os

here = os.path.dirname(os.path.abspath(__file__))
print("/* splash_images.h - generated by mkimages.py: do not edit */")
print()
for name in ("calvin", "ttlogo"):
    rows = [l.rstrip("\n") for l in open(os.path.join(here, name + ".txt")) if l.strip()]
    w, h = len(rows[0]), len(rows)
    stride = (w + 7) // 8
    print("#define %s_WIDTH  %d" % (name.upper(), w))
    print("#define %s_HEIGHT %d" % (name.upper(), h))
    print("#define %s_STRIDE %d" % (name.upper(), stride))
    print()
    print("static const uint8_t g_%s[%d] =" % (name, stride * h))
    print("{")
    for r in rows:
        r = r.ljust(stride * 8, ".")
        b = [int(r[i:i + 8].replace("#", "1").replace(".", "0"), 2) for i in range(0, stride * 8, 8)]
        print("  " + ", ".join("0x%02x" % v for v in b) + ",")
    print("};")
    print()
